class TextoMalformado(unittest.TestCase):
    CASOS = {
        "entidades_dtd": "KML_DTD_NO_PERMITIDA",
        "entidad_externa": "KML_DTD_NO_PERMITIDA",
        "xml_roto": "KML_XML_INVALIDO",
        "coordenada_con_espacio": "KML_COORDENADAS_INVALIDAS",
        "coordenada_con_guion_bajo": "KML_COORDENADAS_INVALIDAS",
        "coordenada_nan": "KML_COORDENADAS_INVALIDAS",
    }

    def test_cada_caso(self):
        for nombre, codigo in self.CASOS.items():
            with self.subTest(nombre):
                r = procesar(nombre)
                self.assertEqual(r["estado"], kmz.RECHAZADO)
                self.assertEqual(r["error"]["codigo"], codigo)

    def test_xml_truncado_en_cualquier_punto(self):
        texto = kml("poligono_con_hueco")
        for corte in range(1, len(texto) - 10, 37):
            with self.subTest(corte=corte):
                r = kmz.procesar_kmz(empaquetar([("doc.kml", texto[:corte])]))
                self.assertEqual(r["estado"], kmz.RECHAZADO)

    def test_codificacion_desconocida(self):
        texto = kml("poligono_simple").replace(b'encoding="UTF-8"', b'encoding="UTF-Y"')
        r = kmz.procesar_kmz(empaquetar([("doc.kml", texto)]))
        self.assertEqual(r["error"]["codigo"], "KML_CODIFICACION_NO_SOPORTADA")

    def test_codificacion_latin1_declarada(self):
        texto = kml("poligono_simple").decode().replace("UTF-8", "ISO-8859-1")
        texto = texto.replace("Predio Ficticio Uno", "Predio Ficticio Año")
        r = kmz.procesar_kmz(empaquetar([("doc.kml", texto.encode("latin-1"))]))
        self.assertEqual(r["candidatos"][0]["nombre"], "Predio Ficticio Año")

    def test_mutaciones_nunca_lanzan_excepciones(self):
        """Seeded byte mutations of the fixtures, the KML text and the package."""
        rng = random.Random(20261007)
        fuentes = sorted(FIXTURES.glob("*.kml"))
        for vuelta in range(600):
            texto = bytearray(rng.choice(fuentes).read_bytes())
            modo = vuelta % 3
            if modo == 0:
                for _ in range(rng.randint(1, 8)):
                    texto[rng.randrange(len(texto))] = rng.randrange(256)
            datos = bytearray(empaquetar([("doc.kml", bytes(texto))]))
            if modo == 1:
                for _ in range(rng.randint(1, 8)):
                    datos[rng.randrange(len(datos))] = rng.randrange(256)
            elif modo == 2:
                datos = datos[:rng.randrange(len(datos))]
            seleccion = rng.choice([None, [0], [0, 1], [1], [0.0], "x"])
            with self.subTest(vuelta=vuelta):
                r = kmz.procesar_kmz(bytes(datos), seleccion)
                self.assertEqual(set(r), CLAVES)
                json.dumps(r)

    def test_entidad_no_declarada(self):
        r = kmz.procesar_kmz(empaquetar([("doc.kml", documento("<name>&x;</name>"))]))
