class PartesQueSeTocan(unittest.TestCase):
    """Axis-aligned rectangles in units of 0.001°, so every predicate is exact."""

    @staticmethod
    def r(x0, y0, x1, y1):
        u = 0.001
        a, b, c, d = LON + x0 * u, LAT + y0 * u, LON + x1 * u, LAT + y1 * u
        return [(a, b), (c, b), (c, d), (a, d), (a, b)]

    def codigo(self, *poligonos):
        error = kmz.validar_poligonos(list(poligonos))
        return error.codigo if error else None

    def test_borde_compartido_completo_o_parcial(self):
        self.assertIsNone(self.codigo([self.r(0, 0, 2, 1)], [self.r(2, 0, 4, 1)]))
        self.assertIsNone(self.codigo([self.r(0, 0, 2, 1)], [self.r(1, 1, 3, 2)]))
        self.assertIsNone(self.codigo([self.r(0, 0, 2, 1)], [self.r(2, 1, 3, 2)]))  # a corner

    def test_encimados_que_solo_comparten_bordes_colineales(self):
        self.assertEqual(self.codigo([self.r(0, 0, 2, 1)], [self.r(1, 0, 3, 1)]),
                         "GEOMETRIA_PARTES_SUPERPUESTAS")
        self.assertEqual(self.codigo([self.r(0, 0, 2, 1)], [self.r(1.99, 0, 3, 1)]),
                         "GEOMETRIA_PARTES_SUPERPUESTAS")

    def test_contenido_tocando_el_borde(self):
        self.assertEqual(self.codigo([self.r(0, 0, 1, 1)], [self.r(0, 0, 2, 2)]),
                         "GEOMETRIA_PARTES_SUPERPUESTAS")

    def test_isla_dentro_de_un_hueco(self):
        con_hueco = [self.r(0, 0, 3, 3), self.r(1, 1, 2, 2)]
        self.assertIsNone(self.codigo(con_hueco, [self.r(1, 1, 2, 2)]))
        self.assertEqual(self.codigo(con_hueco, [self.r(1, 1, 2.5, 2)]),
                         "GEOMETRIA_PARTES_SUPERPUESTAS")


